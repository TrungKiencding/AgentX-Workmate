/**
 * Signing in must go straight from the sign-in screen to the app's loading
 * screen — never through the chat shell.
 *
 * The bug: right after the browser came back signed in, the window showed the
 * chat for a moment with a "Desktop boot failed — AgentX sign-in required"
 * toast on it, then switched to the loading screen and signed in normally.
 * The sign-in screen let go of the window as soon as the backend began to
 * restart, while the renderer still held the "sign-in required" error from
 * the last boot — so no full-screen surface owned the window, and the
 * sticky toast raised by that boot (until then hidden under the sign-in
 * screen) was left on top of the chat.
 *
 * The flash ends with a page reload, which wipes anything a test could read
 * afterwards. So every document reports what covers the window on each
 * animation frame through the console, and the spec reads the stream.
 */

import fs from 'node:fs'
import path from 'node:path'

import type { ElectronApplication } from '@playwright/test'

import { FAKE_SSO_CLIENT_ID, FAKE_SSO_REALM, type FakeSso, startFakeSso } from './fake-sso'
import { buildAppEnv, createSandbox, launchDesktop, type Sandbox } from './fixtures'
import { expect, test } from './test'

const SIGN_IN = /Đăng nhập bằng AgentX|Sign in with AgentX/
const TRACE_PREFIX = '[sign-in-trace] '

interface Frame {
  /** performance.timeOrigin — one value per document, so a reload starts a new one. */
  doc: number
  t: number
  clicked: boolean
  signIn: boolean
  connecting: boolean
  bootFailure: boolean
  keyGate: boolean
  composer: boolean
  alerts: string[]
}

function writeSsoConfig(sandbox: Sandbox, sso: FakeSso): void {
  fs.writeFileSync(
    path.join(sandbox.hermesHome, 'config.yaml'),
    [
      '# Auto-generated by sign-in-transition.spec.ts — signs in against fake-sso.ts',
      'dashboard:',
      '  oauth:',
      '    keycloak:',
      `      base_url: ${sso.url}`,
      `      realm: ${FAKE_SSO_REALM}`,
      `      client_id: ${FAKE_SSO_CLIENT_ID}`,
      'accounts:',
      '  keys:',
      `    base_url: ${sso.url}`,
      'display:',
      '  language: en',
      'security:',
      '  tirith_enabled: false',
      ''
    ].join('\n'),
    'utf8'
  )
}

/** A browser holding a live SSO session redirects straight back; so does this. */
async function routeSignInThroughFetch(app: ElectronApplication): Promise<void> {
  await app.evaluate(({ shell }) => {
    shell.openExternal = async (url: string) => {
      await fetch(url, { redirect: 'follow' }).catch(() => undefined)
    }
  })
}

test('signing in goes from the sign-in screen to the loading screen without showing the chat or an error', async () => {
  test.setTimeout(420_000)

  const sso = await startFakeSso({ name: 'Sign In Transition' })
  const sandbox = createSandbox('sign-in-transition')
  let app: ElectronApplication | undefined

  // Issued at once, so the key gate does not stand between sign-in and the app.
  sso.setKeys('issue')

  try {
    writeSsoConfig(sandbox, sso)

    const launched = await launchDesktop(
      buildAppEnv(sandbox, {
        AGENTX_DASHBOARD_KEYCLOAK_BASE_URL: sso.url,
        AGENTX_DASHBOARD_KEYCLOAK_CLIENT_ID: FAKE_SSO_CLIENT_ID,
        AGENTX_DASHBOARD_KEYCLOAK_REALM: FAKE_SSO_REALM
      })
    )

    app = launched.app
    const { page } = launched
    const frames: Frame[] = []

    page.on('console', message => {
      const text = message.text()

      if (text.startsWith(TRACE_PREFIX)) {
        frames.push(JSON.parse(text.slice(TRACE_PREFIX.length)) as Frame)
      }
    })

    // Runs in every document from here on — the reload after sign-in included.
    const recorder = (prefix: string) => {
      let last = ''

      const tick = () => {
        const editor = document.querySelector<HTMLElement>('[contenteditable="true"]')

        const frame = {
          doc: performance.timeOrigin,
          t: Date.now(),
          clicked: Boolean((window as unknown as { __signInClicked?: boolean }).__signInClicked),
          signIn: Boolean(document.querySelector('.sign-in-screen')),
          connecting: Boolean(document.querySelector('[data-slot="connecting-splash"]')),
          bootFailure: Boolean(document.querySelector('#boot-failure-steps')),
          keyGate: Boolean(document.querySelector('#agentx-key-gate-title')),
          composer: Boolean(editor && editor.getClientRects().length > 0),
          alerts: [...document.querySelectorAll('[role="alert"]')]
            .map(node => (node.textContent ?? '').trim())
            .filter(Boolean)
        }

        const key = JSON.stringify({ ...frame, t: 0 })

        if (key !== last) {
          last = key
          console.log(prefix + JSON.stringify(frame))
        }

        requestAnimationFrame(tick)
      }

      requestAnimationFrame(tick)
    }

    await page.addInitScript(recorder, TRACE_PREFIX)
    // The first document loaded before the init script was registered.
    await page.evaluate(recorder, TRACE_PREFIX)

    await routeSignInThroughFetch(app)

    const button = page.getByRole('button', { name: SIGN_IN })

    await button.waitFor({ state: 'visible', timeout: 180_000 })
    const signInDoc = await page.evaluate(() => performance.timeOrigin)

    await page.evaluate(() => {
      ;(window as unknown as { __signInClicked?: boolean }).__signInClicked = true
    })
    await button.click()

    // Signed in, reloaded, booted: the app is in front of the person.
    await page.waitForSelector('[contenteditable="true"]', { state: 'visible', timeout: 240_000 })
    await expect(page.locator('.sign-in-screen')).toHaveCount(0)
    await expect(page.locator('#agentx-key-gate-title')).toHaveCount(0)

    // Let the last frames of the final document reach the console listener.
    await page.waitForTimeout(500)

    const afterClick = frames.filter(frame => frame.doc === signInDoc && frame.clicked)
    const finalDocs = new Set(frames.filter(frame => frame.doc !== signInDoc).map(frame => frame.doc))

    // The sign-in reloads the window once it has a session.
    expect(afterClick.length).toBeGreaterThan(0)
    expect(finalDocs.size).toBeGreaterThan(0)

    // Until that reload, something full-screen owns the window at every frame:
    // the sign-in screen holding its "signed in, reconnecting" state, or the
    // loading screen. Never the chat shell behind them.
    const exposed = afterClick.filter(
      frame => !frame.signIn && !frame.connecting && !frame.bootFailure && !frame.keyGate
    )

    expect(exposed, `chat shell exposed before the reload:\n${JSON.stringify(exposed, null, 2)}`).toEqual([])

    // Nor is anything raised as an error along the way, in any document. The
    // sign-in screen's own inline error is role="alert" too, so this also
    // proves the sign-in itself did not fail.
    const alerts = [...new Set(frames.flatMap(frame => frame.alerts))]

    expect(alerts).toEqual([])
  } finally {
    await app?.close().catch(() => undefined)
    await sso.close()
    sandbox.cleanup()
  }
})
