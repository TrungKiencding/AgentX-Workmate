/** Arabic noun agreement: 1, 2, 3–10, 11+ (digits are used from 3 up). */
function counted(n: number, one: string, two: string, few: string, many: string): string {
  if (n === 1) {
    return one
  }

  if (n === 2) {
    return two
  }

  const tail = n % 100

  return `${n} ${tail >= 3 && tail <= 10 ? few : many}`
}

