#!/usr/bin/env python3
"""Derive terminal artwork from the canonical mark; --check detects drift."""

import argparse
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]


def outputs() -> dict[Path, str]:
    alpha = Image.open(ROOT / "assets/brand/mark-1024.png").getchannel("A")
    alpha = alpha.crop(alpha.getbbox()).resize((28, 32), Image.Resampling.LANCZOS)
    rows = []
    for y in range(0, alpha.height, 2):
        rows.append(
            "".join(
                " ▀▄█"[
                    (alpha.getpixel((x, y)) >= 96)
                    + 2 * (alpha.getpixel((x, y + 1)) >= 96)
                ]
                for x in range(alpha.width)
            )
        )
    header = (
        "Generated by scripts/make_terminal_brand.py from assets/brand/mark-1024.png."
    )
    return {
        ROOT / "hermes_cli/terminal_brand.py": f'"""{header}"""\n\nMARK_ART = (\n'
        + "".join(f"    {row!r},\n" for row in rows)
        + ")\n",
        ROOT / "ui-tui/src/brand-mark.ts": f"// {header}\nexport const MARK_ART = "
        + "[\n"
        + ",\n".join(f"  {row!r}" for row in rows)
        + "\n]\n",
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, expected in outputs().items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != expected:
                raise SystemExit(f"Stale terminal brand: {path.relative_to(ROOT)}")
        else:
            path.write_text(expected, encoding="utf-8")


if __name__ == "__main__":
    main()
